// Writes a construction out as a runnable pydna script, so the steps taken in the
// workbench can go into a paper's supplementary code or a notebook.
//
// A step is only emitted as real code when everything it needs is in the export; the
// rest are written as the recorded sequence with a TODO beside them. Every product ends
// with an assertion against the sequence GATC recorded, so running the script is itself
// the check that the translation was faithful.
import type { CloningHistoryNode, PlasmidDocument, Primer } from '../../types/schema';

export interface PydnaScript {
  code: string;
  warnings: string[];
  /** Products rebuilt by real pydna calls. */
  reproduced: number;
  /** Products written out as a literal sequence because the step could not be expressed. */
  literal: number;
}

/** A python identifier for a document, unique within the script. */
function identifiers(docs: PlasmidDocument[]): Map<string, string> {
  const used = new Set<string>(['pcr', 'parse', 'Dseqrecord', 'Assembly', 'print', 'len', 'str']);
  const map = new Map<string, string>();
  for (const doc of docs) {
    let base = doc.name.replace(/[^A-Za-z0-9_]/g, '_').replace(/^(\d)/, '_$1');
    if (!base) base = 'sequence';
    let name = base;
    let n = 2;
    while (used.has(name)) {
      name = `${base}_${n}`;
      n += 1;
    }
    used.add(name);
    map.set(doc.id, name);
  }
  return map;
}

function pythonString(text: string): string {
  // A raw triple-quoted string keeps the GenBank text exactly as it is.
  return `r"""${text.replace(/"""/g, '\\"\\"\\"')}"""`;
}

function lastNode(history: CloningHistoryNode[]): CloningHistoryNode | undefined {
  for (let index = history.length - 1; index >= 0; index -= 1) {
    if (history[index].operation !== 'manual_edit') return history[index];
  }
  return undefined;
}

const HEADER = `#!/usr/bin/env python3
# Generated by GATC. Reproduces the construction with pydna; run it to check the steps.
#   pip install pydna
"""Each product is rebuilt from its parents and then compared with the sequence GATC
recorded. The script fails loudly if any step does not give that sequence back."""
from Bio import Restriction
from pydna.amplify import pcr
from pydna.dseqrecord import Dseqrecord
from pydna.parsers import parse


def gb(text):
    """One GenBank record, inlined so the script needs no files and no network."""
    (record,) = parse(text)
    return record


def same(made, recorded):
    """Equal sequences, letting a circular molecule start anywhere."""
    a = str(made.seq).upper()
    b = str(recorded.seq).upper()
    if len(a) != len(b):
        return False
    if getattr(made.seq, "circular", False) or getattr(recorded.seq, "circular", False):
        return b in (a + a)
    return a == b


def check(name, made, recorded):
    if not same(made, recorded):
        raise AssertionError(
            f"{name}: rebuilt {len(made)} bp does not match the {len(recorded)} bp GATC recorded"
        )
    print(f"ok  {name}  {len(recorded)} bp")

`;

/**
 * Turn the open documents and their history into a pydna script.
 * `toGenBank` is passed in so this module does not need the GenBank writer itself.
 */
export function exportPydnaScript(
  docs: PlasmidDocument[],
  options: { toGenBank: (doc: PlasmidDocument) => string; title?: string },
): PydnaScript {
  const warnings: string[] = [];
  const names = identifiers(docs);
  const byId = new Map(docs.map((doc) => [doc.id, doc]));
  const lines: string[] = [HEADER];
  if (options.title) lines.push(`# ${options.title}\n`);

  let reproduced = 0;
  let literal = 0;

  for (const doc of docs) {
    const variable = names.get(doc.id)!;
    const node = lastNode(doc.history);
    const recorded = `${variable}_recorded`;
    lines.push(`# ---- ${doc.name} · ${doc.length} bp · ${doc.topology === 'circular' ? 'circular' : 'linear'} ----`);
    lines.push(`${recorded} = gb(${pythonString(options.toGenBank(doc))})`);

    const parents = (node?.parentSnapshots ?? [])
      .map((snapshot) => ({ snapshot, doc: byId.get(snapshot.id) }))
      .filter((entry): entry is { snapshot: NonNullable<typeof entry.snapshot>; doc: PlasmidDocument } => !!entry.doc);
    const allParentsPresent = parents.length === (node?.parentSnapshots ?? []).length && parents.length > 0;

    const emitted = node && allParentsPresent ? emitStep(doc, node, parents, names, variable, lines) : null;
    if (emitted) {
      reproduced += 1;
      lines.push(`check(${JSON.stringify(doc.name)}, ${variable}, ${recorded})`);
    } else {
      if (node && node.operation !== 'import') {
        const reason = allParentsPresent
          ? `pydna 没有直接对应的写法（${node.operation}）`
          : '亲本不在导出范围内';
        warnings.push(`${doc.name}：${reason}，脚本里按已记录的序列直接给出。`);
        lines.push(`# TODO: ${node.description}`);
        lines.push(`#       ${reason}；下面这条是 GATC 记录的产物序列。`);
        literal += 1;
      }
      lines.push(`${variable} = ${recorded}`);
    }
    lines.push('');
  }

  lines.push('print("all steps reproduced")');
  return { code: `${lines.join('\n')}\n`, warnings, reproduced, literal };
}

/** Emits the pydna call for one step, or returns null when there is no faithful one. */
function emitStep(
  doc: PlasmidDocument,
  node: CloningHistoryNode,
  parents: Array<{ snapshot: { id: string; name: string }; doc: PlasmidDocument }>,
  names: Map<string, string>,
  variable: string,
  lines: string[],
): boolean {
  const parentVar = (index: number) => names.get(parents[index].doc.id)!;

  if (node.operation === 'pcr' && parents.length === 1) {
    const used = node.primersUsed ?? [];
    const forward = findPrimer(doc, used, 1);
    const reverse = findPrimer(doc, used, -1);
    if (!forward || !reverse) return false;
    lines.push(`# ${node.description}`);
    lines.push(`${variable}_fwd = ${JSON.stringify(forward.sequence)}  # ${forward.name}`);
    lines.push(`${variable}_rev = ${JSON.stringify(reverse.sequence)}  # ${reverse.name}`);
    lines.push(`${variable} = pcr(${variable}_fwd, ${variable}_rev, ${parentVar(0)})`);
    return true;
  }

  if (node.operation === 'restriction_ligation' && node.enzymesUsed?.length) {
    const enzymes = node.enzymesUsed.filter((name) => /^[A-Za-z][A-Za-z0-9]*$/.test(name));
    if (!enzymes.length) return false;
    lines.push(`# ${node.description}`);
    lines.push(`${variable}_enzymes = [${enzymes.map((e) => `Restriction.${e}`).join(', ')}]`);
    // Only "cut this plasmid and close it again" can be written down from what the
    // history records; a ligation of fragments that were cut earlier would need to know
    // which fragment went where, and guessing would produce a script that runs and lies.
    if (parents.length === 1 && parents[0].doc.topology === 'circular' && doc.topology === 'circular') {
      lines.push(`${variable}_fragments = ${parentVar(0)}.cut(*${variable}_enzymes)`);
      lines.push(`${variable} = ${variable}_fragments[0]`);
      lines.push(`for _piece in ${variable}_fragments[1:]:`);
      lines.push(`    ${variable} = ${variable} + _piece`);
      lines.push(`${variable} = ${variable}.looped()`);
      return true;
    }
    return false;
  }

  if (node.operation === 'oligo_annealing') {
    return false;
  }

  return false;
}

function findPrimer(doc: PlasmidDocument, used: string[], strand: 1 | -1): Primer | undefined {
  const candidates = doc.primers.filter((primer) => used.includes(primer.name));
  return candidates.find((primer) => primer.strand === strand);
}
