"""Regenerates src/modules/seq-engine/rebase-overrides.ts from REBASE data (via Biopython's
Restriction_Dictionary) for every enzyme whose GATC definition disagrees with REBASE.

Usage: python gen_rebase_overrides.py gatc-algos.json > src/modules/seq-engine/rebase-overrides.ts
(gatc-algos.json must be produced from a build *without* the overrides applied, or with them —
the comparison is idempotent because applied overrides already match REBASE.)
"""
import json
import sys

from Bio.Restriction import AllEnzymes

gatc = {e["name"]: e for e in json.load(open(sys.argv[1]))["enzymes"]}
rebase = {str(e): e for e in AllEnzymes}
overrides, unknown = {}, []
for name, g in sorted(gatc.items()):
    e = rebase.get(name)
    if e is None:
        continue
    if e.is_unknown():
        unknown.append(name)
        continue
    fst5, fst3, scd5, scd3, site = e.charac
    n = len(site)
    want = {"recognitionSeq": site.upper(), "cutIndexTop": fst5, "cutIndexBottom": n + fst3}
    if scd5 is not None:
        want["secondCut"] = {"top": scd5, "bottom": n + scd3}
    have = {"recognitionSeq": g["site"].upper(), "cutIndexTop": g["top"], "cutIndexBottom": g["bottom"]}
    if g.get("secondCut"):
        have["secondCut"] = g["secondCut"]
    if want != have:
        overrides[name] = want

print("// Generated by scripts/crosscheck/gen_rebase_overrides.py from REBASE (Biopython")
print("// Restriction_Dictionary). Corrects enzymes whose upstream definition disagrees with")
print("// REBASE, adds the upstream cut of enzymes that cleave on both sides of their site, and")
print("// lists enzymes whose cut position REBASE does not know. Do not edit by hand.")
print()
print("export interface RebaseOverride {")
print("  recognitionSeq: string;")
print("  cutIndexTop: number;")
print("  cutIndexBottom: number;")
print("  secondCut?: { top: number; bottom: number };")
print("}")
print()
print("export const REBASE_OVERRIDES: Record<string, RebaseOverride> = {")
for name, o in overrides.items():
    second = f", secondCut: {{ top: {o['secondCut']['top']}, bottom: {o['secondCut']['bottom']} }}" if "secondCut" in o else ""
    print(f"  {json.dumps(name)}: {{ recognitionSeq: '{o['recognitionSeq']}', cutIndexTop: {o['cutIndexTop']}, cutIndexBottom: {o['cutIndexBottom']}{second} }},")
print("};")
print()
print("export const REBASE_UNKNOWN_CUT: ReadonlySet<string> = new Set([")
for i in range(0, len(unknown), 6):
    print("  " + ", ".join(f"'{u}'" for u in unknown[i:i + 6]) + ",")
print("]);")
